            if payload["level_code"] == 3:
                now = time.time()
                if level3_start_time is None:
                    level3_start_time = now

                elapsed = now - level3_start_time
                if elapsed > 5.0:
                    payload["cluster_level"] = "Level 3 (Bahaya)"
                else:
                    payload["cluster_level"] = "Level 3"
            else:
                level3_start_time = None

